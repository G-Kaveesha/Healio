def normalize_emotion_label(
    emotion
):

    if not isinstance(
        emotion,
        str
    ):
        return ""

    return (
        emotion
        .strip()
        .lower()
    )


def get_candidates_for_emotion(
    emotion: str
):

    normalized_emotion = (
        normalize_emotion_label(
            emotion
        )
    )


    activity_ids = (
        EMOTION_ACTIVITY_MAP.get(
            normalized_emotion,
            []
        )
    )


    candidates = []


    for activity_id in activity_ids:

        activity = (
            ACTIVITY_BY_ID.get(
                activity_id
            )
        )

        if activity:

            candidates.append(
                activity
            )


    return candidates



def get_activity_by_id(
    activity_id
):

    if not isinstance(
        activity_id,
        str
    ):
        return None


    clean_id = (
        activity_id
        .strip()
        .lower()
    )


    if not clean_id:
        return None


    return ACTIVITY_BY_ID.get(
        clean_id
    )



def get_sleep_track_by_id(
    track_id
):

    if not isinstance(
        track_id,
        str
    ):
        return None


    clean_id = (
        track_id
        .strip()
        .lower()
    )


    if not clean_id:
        return None


    return SLEEP_TRACK_BY_ID.get(
        clean_id
    )


def get_recommendation_by_id(
    recommendation_id
):

    if not isinstance(
        recommendation_id,
        str
    ):
        return None


    clean_id = (
        recommendation_id
        .strip()
        .lower()
    )


    if not clean_id:
        return None


    return (
        ALL_RECOMMENDATIONS_BY_ID
        .get(
            clean_id
        )
    )

def is_valid_activity_id(
    activity_id
):

    return (
        get_activity_by_id(
            activity_id
        )
        is not None
    )


def is_valid_sleep_track_id(
    track_id
):

    return (
        get_sleep_track_by_id(
            track_id
        )
        is not None
    )


def is_valid_recommendation_id(
    recommendation_id
):

    return (
        get_recommendation_by_id(
            recommendation_id
        )
        is not None
    )



def activity_for_client(
    activity
):

    if not activity:
        return None


    result = {
        "id":
            activity["id"],

        "title":
            activity["title"],

        "category":
            activity["category"],

        "type":
            activity["type"],

        "duration":
            activity.get(
                "duration"
            ),

        "activityScreen":
            activity[
                "activityScreen"
            ],
    }


    if activity.get(
        "subtitle"
    ):

        result[
            "subtitle"
        ] = activity[
            "subtitle"
        ]


    return result


def get_sleep_tracks_for_client():

    return [
        activity_for_client(
            track
        )
        for track in SLEEP_TRACKS
    ]


def get_client_candidates_for_emotion(
    emotion: str
):

    candidates = (
        get_candidates_for_emotion(
            emotion
        )
    )


    return [
        activity_for_client(
            activity
        )
        for activity
        in candidates
    ]